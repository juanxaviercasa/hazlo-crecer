import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const brand = JSON.parse(fs.readFileSync(path.join(root, 'public/assets/brand/manifest.json'), 'utf8'));
const roles = {
  primary: 'brand-primary', primary_hover: 'brand-primary-hover', accent: 'brand-accent',
  background: 'brand-background', surface: 'brand-surface', text: 'brand-text',
  muted: 'brand-muted', border: 'brand-border', logo_background: 'brand-logo-background',
  on_primary: 'brand-on-primary'
};
if (brand.brand_id !== 'hazlo-crecer' || brand.logo_status !== 'approved_for_use_v1') {
  throw new Error('Unexpected brand identity; review before publishing.');
}
for (const role of Object.keys(roles)) {
  if (!/^#[0-9a-f]{6}$/i.test(brand.palette[role] || '')) throw new Error(`Invalid brand color: ${role}`);
}
for (const asset of Object.values(brand.assets)) {
  if (!asset.startsWith('/assets/brand/') || asset.includes('..') || !fs.existsSync(path.join(root, 'public', asset))) {
    throw new Error('Missing or invalid brand asset');
  }
}
const css = `/* Generated by scripts/sync-brand.mjs from the public brand manifest. */\n:root {\n${Object.entries(roles).map(([role, token]) => `  --${token}: ${brand.palette[role]};`).join('\n')}\n}\n`;
const target = path.join(root, 'src/brand-tokens.css');
if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== css) fs.writeFileSync(target, css);
console.log(`Brand ${brand.brand_id} identity ${brand.identity_version}: assets and palette validated.`);
